#!/usr/bin/env bash
# Regenerate crates/bench/src/load/defi_bytecode.rs from the compiled
# artifacts. Run after changing BenchDefi.sol: forge build && ./embed.sh
set -euo pipefail
cd "$(dirname "$0")"
~/.foundry/bin/forge build >/dev/null
python3 - <<'PY'
import json
names = ["SwapPool", "Vault", "Clob"]
with open("../../crates/bench/src/load/defi_bytecode.rs", "w") as f:
    f.write("// GENERATED by contracts/bench/embed.sh — do not edit.\n")
    f.write("// Source of truth: contracts/bench/src/BenchDefi.sol\n\n")
    for n in names:
        j = json.load(open(f"out/BenchDefi.sol/{n}.json"))
        code = j["bytecode"]["object"].removeprefix("0x")
        f.write(f'pub const {n.upper()}_CREATION_HEX: &str = "{code}";\n')
print("ok")
PY
